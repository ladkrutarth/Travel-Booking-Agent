export function projectEquirectangular(
  lat: number,
  lon: number,
  width: number,
  height: number,
  pad = 24,
): { x: number; y: number } {
  const x = pad + ((lon + 180) / 360) * (width - pad * 2);
  const y = pad + ((90 - lat) / 180) * (height - pad * 2);
  return { x, y };
}
